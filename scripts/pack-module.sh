#!/usr/bin/env bash
# 把一个已签名的 APK 打包成可刷入的 Magisk / KernelSU / APatch 模块。
#
# 用法: pack-module.sh <variant> <apk> <tag> <version_code> [outdir]
#   variant: aosp | google | samsung
#
# 产物: <outdir>/InstallerX-Revived-<LABEL>-<tag>.zip
set -euo pipefail

VARIANT=${1:?variant}
APK=${2:?apk}
TAG=${3:?tag}
CODE=${4:?version_code}
OUTDIR=${5:-build}

case "$VARIANT" in
  aosp)
    PKG=com.android.packageinstaller
    DIR=PackageInstaller
    APKNAME=PackageInstaller.apk
    LABEL=AOSP
    ;;
  google)
    PKG=com.google.android.packageinstaller
    DIR=GooglePackageInstaller
    APKNAME=GooglePackageInstaller.apk
    LABEL=Google
    ;;
  samsung)
    PKG=com.samsung.android.packageinstaller
    DIR=PackageInstaller_CHN
    APKNAME=PackageInstaller_CHN.apk
    LABEL=Samsung
    ;;
  *)
    echo "unknown variant: $VARIANT" >&2
    exit 1
    ;;
esac

[ -f "$APK" ] || { echo "apk not found: $APK" >&2; exit 1; }

REPO=${GITHUB_REPOSITORY:?GITHUB_REPOSITORY not set}
OWNER=${GITHUB_REPOSITORY_OWNER:-${REPO%%/*}}
UPSTREAM=${UPSTREAM:-wxxsfxyzm/InstallerX-Revived}

# 找 aapt2（本地 Windows 下是 aapt2.exe）
AAPT2=${AAPT2:-}
if [ -z "$AAPT2" ]; then
  for c in "$ANDROID_HOME"/build-tools/*/aapt2 "$ANDROID_HOME"/build-tools/*/aapt2.exe; do
    [ -x "$c" ] && AAPT2=$c
  done
fi
[ -n "$AAPT2" ] && [ -x "$AAPT2" ] || { echo "aapt2 not found" >&2; exit 1; }

STAGE=$(mktemp -d)
trap 'rm -rf "$STAGE"' EXIT

MOD="$STAGE/module"
cp -a module "$MOD"

# 系统安装器的目标路径
TARGET="$MOD/system/priv-app/$DIR"
mkdir -p "$TARGET/oat" "$TARGET/lib"
# 屏蔽原厂 odex/lib，避免它们跟被替换的 APK 配对
touch "$TARGET/oat/.replace" "$TARGET/lib/.replace"
cp "$APK" "$TARGET/$APKNAME"

# 用 APK 实际声明的权限生成 privapp 白名单。
# 必须覆盖 APK 请求的全部特权权限，否则 enforce 模式的 ROM 会直接拒装这个包；
# 多列几个普通权限只会产生日志告警，不会有副作用。
PERMS_XML="$MOD/system/etc/permissions/privapp-permissions-installerx-$VARIANT.xml"
mkdir -p "$(dirname "$PERMS_XML")"
{
  echo '<?xml version="1.0" encoding="utf-8"?>'
  echo "<!-- Generated by InstallerX-Revived module build ($LABEL / $PKG / $TAG) -->"
  echo '<permissions>'
  echo "    <privapp-permissions package=\"$PKG\">"
  "$AAPT2" dump badging "$APK" \
    | sed -n "s/^uses-permission: name='\(android\.permission\.[^']*\)'.*/\1/p" \
    | sort -u \
    | while read -r p; do echo "        <permission name=\"$p\"/>"; done
  echo '    </privapp-permissions>'
  echo '</permissions>'
} > "$PERMS_XML"

# 渲染模板里的占位符
render() {
  sed -e "s|@PKG@|$PKG|g" \
      -e "s|@DIR@|$DIR|g" \
      -e "s|@APK@|$APKNAME|g" \
      -e "s|@LABEL@|$LABEL|g" \
      -e "s|@VARIANT@|$VARIANT|g" \
      -e "s|@TAG@|$TAG|g" \
      -e "s|@CODE@|$CODE|g" \
      -e "s|@OWNER@|$OWNER|g" \
      -e "s|@REPO@|$REPO|g" \
      -e "s|@UPSTREAM@|$UPSTREAM|g" \
      "$1"
}

for f in customize.sh action.sh uninstall.sh service.sh; do
  render "$MOD/$f" > "$MOD/$f.tmp" && mv "$MOD/$f.tmp" "$MOD/$f"
  chmod 0755 "$MOD/$f"
done
render "$MOD/module.prop.in" > "$MOD/module.prop"
rm -f "$MOD/module.prop.in"

# 兜底：模板里若还有未替换的占位符，直接失败，不要发出坏包
if grep -rqE '@[A-Z_]+@' "$MOD"; then
  echo "unresolved placeholder in module tree:" >&2
  grep -rnE '@[A-Z_]+@' "$MOD" >&2
  exit 1
fi

ZIPNAME="InstallerX-Revived-$LABEL-$TAG.zip"
mkdir -p "$OUTDIR"
rm -f "$OUTDIR/$ZIPNAME"

if command -v zip >/dev/null 2>&1; then
  (cd "$MOD" && zip -r9 -X "$OLDPWD/$OUTDIR/$ZIPNAME" . >/dev/null)
else
  (cd "$MOD" && python3 -m zipfile -c "$OLDPWD/$OUTDIR/$ZIPNAME" .)
fi

echo "packed: $OUTDIR/$ZIPNAME"
ls -l "$OUTDIR/$ZIPNAME"
